export function series(period = "Today") {
  const actual = [
    2, 4, 2, 2, 27, 18, 4, 2, 2, 4, 6, 4, 9, 12, 20, 26, 34, 42, 46, 38, 20, 14,
    2,
  ];
  const forecast = [
    0, 1, 1, 5, 1, 1, 0, 1, 1, 0, 1, 7, 0, 8, 1, 0, 1, 1, 0, 1, 1, 5, 1, 1, 0,
  ];
  const target = period === "7 days" ? 2248 : period === "30 days" ? 9430 : 340;
  function distribute(weights, total) {
    const sum = weights.reduce((a, b) => a + b, 0);
    let cumulative = 0;
    return weights.map((weight) => {
      const prev = Math.round((cumulative * total) / sum);
      cumulative += weight;
      return Math.round((cumulative * total) / sum) - prev;
    });
  }
  const done = distribute(actual, target),
    planned = distribute(forecast, Math.round((target * 61) / 340));
  const lanes = [259, 1, 6, 2, 14, 58],
    counts = distribute(lanes, target);
  return [...done, ...planned].map((value, i) => ({
    hour: i / 2,
    value,
    planned: i >= 23,
    failed: i === 14 || i === 19,
    queued: i >= 19 && i <= 21,
    level: i < 23 ? actual[i] : forecast[i - 23] * 1.6,
    expected: [42, 44, 44][i - 19] || 0,
    counts,
  }));
}
export function esc(value) {
  return String(value).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
}

